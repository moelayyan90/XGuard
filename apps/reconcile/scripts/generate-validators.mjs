import { readFile, mkdir, writeFile } from "node:fs/promises";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { bazaarResourceServerExtension } from "@x402/extensions/bazaar";
import discovery from "../src/discovery.js";
import { schemaKey } from "../src/schema-key.js";

// Match @x402/extensions 2.24.0's validation options. Compilation and schema
// meta-validation run here in Node at build time, never in the Worker.
const ajv = new Ajv2020({ strict: false, allErrors: true, code: { source: true, esm: true, lines: true } });
const declared = discovery.bazaar;
const enriched = bazaarResourceServerExtension.enrichDeclaration(declared, {
  method: "GET",
  routePattern: "/v1/reconcile",
  adapter: { getPath: () => "/v1/reconcile" }
});
const schemas = { validateDeclaredDiscovery: declared.schema, validateGetDiscovery: enriched.schema };
for (const [name, schema] of Object.entries(schemas)) ajv.addSchema(schema, name);
// Catch declaration/schema drift at build time, too. The SDK synthesizes this
// method for startup validation, without changing the advertised declaration.
if (!ajv.getSchema("validateDeclaredDiscovery")({ ...declared.info, input: { ...declared.info.input, method: "GET" } }) ||
    !ajv.getSchema("validateGetDiscovery")(enriched.info)) {
  throw new Error("Invalid Bazaar discovery declaration");
}
const output = "// Generated by scripts/generate-validators.mjs. Do not edit.\n" +
  standaloneCode(ajv, Object.fromEntries(Object.keys(schemas).map(name => [name, name]))) +
  `\nexport const validators = new Map([\n${Object.entries(schemas).map(([name, schema]) => `  [${JSON.stringify(schemaKey(schema))}, ${name}]`).join(",\n")}\n]);\n`;
const target = new URL("../src/generated/bazaar-validators.js", import.meta.url);
if (process.argv.includes("--check")) {
  const current = await readFile(target, "utf8").catch(() => "");
  if (current !== output) throw new Error("Standalone Bazaar validators are stale; run npm run generate:validators");
} else {
  await mkdir(new URL("../src/generated/", import.meta.url), { recursive: true });
  await writeFile(target, output);
}
