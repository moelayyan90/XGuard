import Ajv from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { discovery } from '../src/index.js';
import { schemaKey } from '../src/schema-key.js';

const ajv = new Ajv({ strict: false, allErrors: true, code: { source: true, esm: true } });
const validate = ajv.compile(discovery.bazaar.schema);
if (!validate({ ...discovery.bazaar.info, input: { ...discovery.bazaar.info.input, method: 'GET' } })) throw new Error(JSON.stringify(validate.errors));
const directory = new URL('../src/generated/', import.meta.url);
const files = new Map([
  ['discovery-validator.js', '// Generated by scripts/generate-validators.mjs; do not edit.\n' + standaloneCode(ajv, validate) + '\n'],
  ['discovery-schema-key.js', '// Generated from the exact declared Bazaar schema.\nexport const discoverySchemaKey = ' + JSON.stringify(schemaKey(discovery.bazaar.schema)) + ';\n'],
]);
if (!process.argv.includes('--check')) await mkdir(directory, { recursive: true });
for (const [name, contents] of files) {
  const path = new URL(name, directory);
  if (process.argv.includes('--check')) {
    if (await readFile(path, 'utf8') !== contents) throw new Error(`Generated validator is stale: ${fileURLToPath(path)}`);
  } else await writeFile(path, contents);
}
console.log('Exact Bazaar schema compiled and validated at build time.');
